package tracking

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"net/http"
	"strconv"
	"strings"
	"time"
)

// ErrNotFound covers absent, expired and revoked capabilities. It must not
// disclose whether a capability was ever valid.
var ErrNotFound = errors.New("tracking capability unavailable")

// Visitor records analytics for a link whose ciphertext already decrypted; it
// never resolves the link and never sees a destination. For a GET it must
// durably record the event and any webhook effects before returning until the
// snapshotted event limit is reached; later requests record nothing further.
// HEAD requests use record=false and must not create an event. Implementations
// must enforce expiration, revocation and bounded event volume. Errors must not
// carry tokens or message content; the handler ignores them (best effort).
type Visitor interface {
	Visit(context.Context, [32]byte, string, bool) error
}

// Handler decrypts self-contained v2 links independently of analytics storage.
// Only /t/{o|c|u}/v2/... paths are accepted; everything else is 404.
type Handler struct {
	Visitor Visitor
	Origin  string
	Links   *LinkKeys
	// Unsubscribes records one-click unsubscribes. When nil, a verified POST
	// to /t/u gets 503 and GET and HEAD still work.
	Unsubscribes UnsubscribeRecorder
}

// pixel is a fixed transparent 1x1 GIF; it contains no per-recipient data.
var pixel = []byte{
	'G', 'I', 'F', '8', '9', 'a', 1, 0, 1, 0, 0x80, 0, 0,
	0, 0, 0, 0, 0, 0, 0x21, 0xf9, 4, 1, 0, 0, 0, 0,
	0x2c, 0, 0, 0, 0, 1, 0, 1, 0, 0, 2, 2, 0x44, 1, 0, 0x3b,
}

// HashToken converts the 128-bit bearer token generated by Rewrite to its
// storage key. It accepts only the canonical lowercase hexadecimal spelling.
func HashToken(token string) ([32]byte, error) {
	var zero [32]byte
	if len(token) != 32 || token != strings.ToLower(token) {
		return zero, ErrNotFound
	}
	raw, err := hex.DecodeString(token)
	if err != nil || len(raw) != 16 {
		return zero, ErrNotFound
	}
	return sha256.Sum256(raw), nil
}

func (h *Handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	// Set on every response, including errors, and never echo request paths,
	// tokens, query parameters or destination URLs in a response body.
	w.Header().Set("Cache-Control", "no-store, max-age=0")
	w.Header().Set("Referrer-Policy", "no-referrer")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	if isUnsubscribePath(r.URL.Path) {
		h.serveUnsubscribe(w, r)
		return
	}
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		w.Header().Set("Allow", "GET, HEAD")
		w.WriteHeader(http.StatusMethodNotAllowed)
		return
	}
	if r.URL.RawPath != "" || r.URL.RawQuery != "" || r.URL.ForceQuery {
		w.WriteHeader(http.StatusNotFound)
		return
	}
	hash, kind, destination, err := h.Links.verify(h.Origin, r.URL.Path)
	if err != nil {
		w.WriteHeader(http.StatusNotFound)
		return
	}
	// A valid ciphertext is sufficient for the response. Analytics are best
	// effort: missing/retired records or unavailable dependencies cannot break
	// an issued link. Never invent events for absent records.
	if h.Visitor != nil {
		ctx, cancel := context.WithTimeout(r.Context(), time.Second)
		_ = h.Visitor.Visit(ctx, hash, kind, r.Method == http.MethodGet)
		cancel()
	}
	trackingResponse(w, r, kind, destination)
}

func trackingResponse(w http.ResponseWriter, r *http.Request, kind, destination string) {
	if kind == "click" {
		// The destination was decrypted from the link. Validate again before
		// constructing Location.
		if !eligibleDestination(destination) {
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
		w.Header().Set("Location", destination)
		w.Header().Set("Content-Length", "0")
		w.WriteHeader(http.StatusFound)
		return
	}
	if destination != "" {
		w.WriteHeader(http.StatusServiceUnavailable)
		return
	}
	w.Header().Set("Content-Type", "image/gif")
	w.Header().Set("Content-Length", strconv.Itoa(len(pixel)))
	w.WriteHeader(http.StatusOK)
	if r.Method == http.MethodGet {
		_, _ = w.Write(pixel)
	}
}
